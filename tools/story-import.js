/* Garden Wonder — the story importer.

   Reads docs/57-volume-one-script.md and writes DATA.story.script into
   data.js, between the two STORY SCRIPT markers. Doc 57's "How to read this
   file" section is the contract; this is its only reader.

     node tools/story-import.js           parse, write data.js, print a summary
     node tools/story-import.js --check   parse and compare, write nothing;
                                          exits 1 if data.js is stale

   It REFUSES rather than guesses. A fenced chunk, table row or list item it
   does not understand stops the run with the doc's line number and writes
   nothing, because a line the engine silently dropped is a line the writer's
   pass will never know went missing. Prose between chunks is ignored on
   purpose — that is where the doc talks to its human reader.

   The one thing it invents is the PROVISIONAL level of each memory sliver and
   story line: doc 57 gives only a window ("ch2–ch3"), and "the spec places
   them". Until it does, they are spread evenly across their window's levels,
   deterministically, so the same doc always writes the same data. */

