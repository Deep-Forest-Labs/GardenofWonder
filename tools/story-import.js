/* ---------- a spoken line ---------- */
const LINE_RE = /^([A-Z]+)(?: \((think|bubble|chip|strip)\))?(?: \[([a-z]+)\])?: (.*)$/;
const STRIP_RE = /^\((strip)\): (.*)$/;

function parseLine(raw, lineNo) {
  const t = raw.trim();
  const strip = t.match(STRIP_RE);
  if (strip) return { mode: 'strip', text: strip[2].trim() };
  const m = t.match(LINE_RE);
  if (!m) refuse(lineNo, 'not a line the format knows', raw);
  const who = SPEAKERS[m[1]];
  if (!who) refuse(lineNo, `unknown speaker ${m[1]}`, raw);
  const mode = m[2] || (who === 'note' ? 'note' : 'say');
  const mood = m[3] || null;
  if (mood && !MOODS.includes(mood)) refuse(lineNo, `unknown expression [${mood}]`, raw);
  if (mood && POPPY_ONLY.includes(mood) && who !== 'poppy') refuse(lineNo, `[${mood}] is Poppy's alone`, raw);
  if (who !== 'note' && mode !== 'chip' && !mood) refuse(lineNo, 'a spoken line needs an [expression]', raw);
  if (mode === 'think' && who !== 'mara') refuse(lineNo, 'only Mara has a thought cloud', raw);
  if (mode === 'chip' && who !== 'mara') refuse(lineNo, 'only Mara has reply chips', raw);
  if (mode === 'bubble' && who !== 'poppy') refuse(lineNo, 'only Poppy speaks in the garden bubble', raw);
  let text = m[4].trim();
  const line = { who, mode };
  if (mood) line.mood = mood;
  const met = text.match(/\s*`\?met:([a-z]+)`\s*$/) || text.match(/\s*\?met:([a-z]+)\s*$/);
  if (met) { line.met = met[1]; text = text.slice(0, met.index).trim(); }
  if (mode === 'chip') {
    line.chips = text.split(' | ').map((c) => c.trim()).filter(Boolean);
    if (!line.chips.length || line.chips.length > 2) refuse(lineNo, 'a reply is one or two chips', raw);
    line.text = line.chips[0];
  } else {
    line.text = text;
  }
  if (!line.text) refuse(lineNo, 'an empty line', raw);
  return line;
}

/* ---------- fenced chunks ---------- */
let section = '';        // the nearest ## heading, lower-cased
let chunkHead = null;    // { chapter, kind } from a `### chN.kind` markdown heading
let chapter = null;      // the chapter being filled
let scene = null;        // the scene being filled
let pendingCard = null;  // an @card waiting for the next scene
let run = null;          // the run array being filled
let teachStep = null;
let teachOf = null;      // the chapter whose teach chunk is open

function chapterById(id) { return out.chapters.find((c) => c.id === id); }
function closeChapter() {
  if (pendingCard && scene) { scene.endCard = pendingCard; }
  pendingCard = null;
  scene = null;
}

function startRun(chId, kind, lineNo) {
  const ch = chapterById(chId);
  if (!ch) refuse(lineNo, `a ${kind} chunk for ${chId}, which has no chapter header yet`);
  if (!RUN_KINDS.includes(kind)) refuse(lineNo, `unknown chunk kind .${kind}`);
  ch.runs = ch.runs || {};
  if (ch.runs[kind]) refuse(lineNo, `a second ${chId}.${kind} chunk`);
  if (kind === 'teach') { ch.runs.teach = { intro: [] }; run = ch.runs.teach.intro; teachStep = 'intro'; teachOf = ch; }
  else { ch.runs[kind] = []; run = ch.runs[kind]; teachStep = null; }
  scene = null;
}

function parseChangeList(value, lineNo) {
  return value.split(' · ').map((part) => {
    const p = part.trim();
    const m = p.match(/^([a-z-]+):\s*(.+)$/i);
    if (!m) refuse(lineNo, 'an @change item is key:value', p);
    const item = { kind: m[1] };
    const v = m[2].trim().match(/^([^\s(]+)\s*(?:\((.*)\))?$/);
    if (v) { item.value = v[1]; if (v[2]) item.note = v[2]; } else item.value = m[2].trim();
    if (item.kind === 'order') {
      const om = item.value.match(/^([a-z]+)-([a-z]+)$/);
      if (!om) refuse(lineNo, 'order:<villager>-<good or entry>', p);
      item.villager = om[1];
      item.good = om[2] === 'entry' ? null : om[2];
    }
    if (item.kind === 'counter') item.value = Number(item.value);
    return item;
  });
}

function fenceLine(raw, lineNo) {
  const t = raw.trim();
  if (!t) return;
  // A chapter header.
  let m = t.match(/^### (ch\d+) — (.+?)\s*(?:←.*)?$/);
  if (m) {
    closeChapter();
    if (chapterById(m[1])) refuse(lineNo, `chapter ${m[1]} declared twice`);
    chapter = { id: m[1], n: Number(m[1].slice(2)), title: m[2].trim(), level: null, teaser: '', change: [], notes: [], scenes: [] };
    out.chapters.push(chapter);
    run = null;
    return;
  }
  // A scene header, or an in-fence run header.
  m = t.match(/^#### (ch\d+)\.([a-z0-9]+)(?: · (.*))?$/);
  if (m) {
    const [, chId, kind, rest] = m;
    if (/^s\d+$/.test(kind)) {
      const ch = chapterById(chId);
      if (!ch) refuse(lineNo, `scene ${chId}.${kind} before its chapter header`);
      chapter = ch;
      const sc = { id: `${chId}.${kind}`, room: null, faces: [], lines: [] };
      (rest || '').split(' · ').forEach((part) => {
        const kv = part.match(/^(room|faces): (.*)$/);
        if (!kv) refuse(lineNo, 'a scene header carries room: and faces:', t);
        if (kv[1] === 'room') {
          sc.room = kv[2].split(/[\s(]/)[0];
          if (!['garden', 'meadow', 'stand'].includes(sc.room)) refuse(lineNo, `unknown room ${sc.room}`, t);
          const note = kv[2].match(/\((.*)\)/);
          if (note) sc.roomNote = note[1];
        } else {
          sc.faces = kv[2].split(',').map((f) => f.trim());
          sc.faces.forEach((f) => { if (!Object.values(SPEAKERS).includes(f)) refuse(lineNo, `unknown face ${f}`, t); });
        }
      });
      if (!sc.room || sc.faces.length !== 2 || sc.faces[0] !== 'mara') refuse(lineNo, 'a scene is a room and two faces, Mara first', t);
      if (pendingCard) { sc.card = pendingCard; pendingCard = null; }
      ch.scenes.push(sc);
      scene = sc;
      run = null;
      return;
    }
    closeChapter();
    startRun(chId, kind, lineNo);
    return;
  }
  // Chapter tags.
  m = t.match(/^@([a-z-]+)\s+(.*)$/);
  if (m) {
    const [, tag, value] = m;
    if (tag === 'card') {
      if (scene && !scene.lines.length && !scene.card) scene.card = value.trim();
      else pendingCard = value.trim();
      return;
    }
    if (!chapter) refuse(lineNo, `@${tag} outside a chapter`, t);
    if (tag === 'level') {
      const lv = value.match(/~?(\d+)/);
      if (!lv) refuse(lineNo, '@level needs a number', t);
      chapter.level = Number(lv[1]);
      if (/first Turn/.test(value)) chapter.latch = 'turn';
      return;
    }
    if (tag === 'teaser') { chapter.teaser = value.trim(); return; }
    if (tag === 'change') { chapter.change.push(...parseChangeList(value, lineNo)); return; }
    if (tag === 'change-if-built') { chapter.change.push(...parseChangeList(value, lineNo).map((c) => Object.assign(c, { ifBuilt: true }))); return; }
    if (tag === 'note') { chapter.notes.push(value.trim()); return; }
    refuse(lineNo, `unknown tag @${tag}`, t);
  }
  // A stage direction, and its continuation.
  if (/^— /.test(t) || /^—$/.test(t)) {
    const target = scene ? scene.lines : run;
    if (!target) refuse(lineNo, 'a stage direction outside a scene or run', t);
    target.push({ mode: 'stage', text: t.replace(/^—\s*/, '').replace(/\s*—$/, '') });
    return;
  }
  if (/^\s{3,}\S/.test(raw) && !/^\s*step:/.test(raw) && !/^[A-Z(]/.test(t)) {
    const target = scene ? scene.lines : run;
    const last = target && target[target.length - 1];
    if (!last || last.mode !== 'stage') refuse(lineNo, 'an indented line that continues nothing', t);
    last.text = (last.text + ' ' + t.replace(/\s*—$/, '')).trim();
    return;
  }
  // A teach step.
  m = raw.match(/^\s+step:([a-z]+)\s+(.*)$/);
  if (m) {
    if (teachStep === null) refuse(lineNo, 'a step: line outside the teach chunk', t);
    if (!TEACH_STEPS.includes(m[1])) refuse(lineNo, `unknown teach step ${m[1]}`, t);
    if (teachOf.runs.teach[m[1]]) refuse(lineNo, `a second step:${m[1]}`, t);
    teachOf.runs.teach[m[1]] = [parseLine(m[2], lineNo)];
    return;
  }
  // A spoken line.
  const line = parseLine(raw, lineNo);
  if (HERO_TAG.test(line.text)) { out.pending.push(`${(scene && scene.id) || 'run'}: ${line.text}`); return; }
  if (scene) {
    if (line.mode === 'bubble' || line.mode === 'strip') refuse(lineNo, `a (${line.mode}) line inside a scene`, t);
    scene.lines.push(line);
    return;
  }
  if (run) { run.push(line); return; }
  refuse(lineNo, 'a line with nowhere to go', t);
}

/* ---------- list and table sections ---------- */
function splitItems(s) {
  return s.split(' · ').map((x) => x.trim()).filter(Boolean);
}
function stripShipped(items) {
  return items.filter((x) => !/\*\(shipped\)\*\s*$/.test(x)).map((x) => x.replace(/\s*\*\(shipped\)\*\s*$/, ''));
}

/* Levels the doc never gives: spread evenly across the window, deterministically. */
function levelOf(chId) {
  const ch = chapterById(chId);
  if (!ch || ch.level == null) throw new Error(`no level for ${chId}`);
  return ch.level;
}
function spread(items, fromCh, toCh, afterSpan) {
  const lo = levelOf(fromCh);
  const hi = toCh ? levelOf(toCh) : lo + afterSpan;
  const first = lo + 1;
  const room = Math.max(1, hi - first);
  items.forEach((it, i) => { it.level = Math.min(hi - 1, first + Math.floor((i * room) / items.length)); });
}

