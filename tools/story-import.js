let linesWindow = null;
const sliverRows = [];
const lineGroups = [];

let inFence = false;
let fenceStart = 0;
for (let i = 0; i < src.length; i += 1) {
  const raw = src[i];
  const lineNo = i + 1;
  if (/^```/.test(raw)) {
    inFence = !inFence;
    if (inFence) fenceStart = lineNo;
    else if (chunkHead === null && chapter === null && !/how to read/.test(section)) {
      /* a fence with nothing to belong to was refused on its first line */
    }
    if (!inFence && section.startsWith('how to read')) continue;
    continue;
  }
  if (inFence) {
    if (section.startsWith('how to read')) continue;
    // A fence under a `### chN.kind` heading starts that run unless it opens with its own header.
    if (lineNo === fenceStart + 1 && chunkHead) {
      if (!/^\s*#{3,4} ch/.test(raw)) startRun(chunkHead.chapter, chunkHead.kind, lineNo);
      chunkHead = null;
    }
    fenceLine(raw, lineNo);
    continue;
  }
  let m = raw.match(/^## (.*)$/);
  if (m) { section = m[1].toLowerCase(); chunkHead = null; villager = null; linesWindow = null; continue; }
  m = raw.match(/^### (ch\d+)\.([a-z]+) — /);
  if (m) { chunkHead = { chapter: m[1], kind: m[2] }; continue; }
  if (/^### /.test(raw)) {
    chunkHead = null;
    const vm = raw.match(/^### (\w+) — arrives at (ch\d+)$/);
    if (section === 'the villagers' && vm) {
      const id = vm[1].toLowerCase();
      villager = out.villagers[id] = { arrives: vm[2], greet: [], waiting: [], delivered: [], after: {} };
      continue;
    }
    villager = null;
    if (section === 'the villagers' && /^### (Isolde, the Baroness) — arrives at (ch\d+)$/.test(raw)) {
      const im = raw.match(/arrives at (ch\d+)/);
      villager = out.villagers.isolde = { arrives: im[1], greet: [], waiting: [], delivered: [], after: {} };
    }
    continue;
  }

  if (section.startsWith('between chapters — memory slivers')) {
    const row = raw.match(/^\| (m\d+) \| ([^|]+) \| (.+) \|$/);
    if (row) {
      const win = row[2].trim();
      let from; let to;
      const a = win.match(/^after (ch\d+)$/);
      const b = win.match(/^(ch\d+)–(ch\d+)$/);
      if (a) { from = a[1]; to = null; } else if (b) { from = b[1]; to = b[2]; } else refuse(lineNo, 'a sliver window is "after chN" or "chA–chB"', raw);
      let text = row[3].trim();
      const note = text.match(/\s*\*\((.*)\)\*\s*$/);
      if (note) {
        if (HERO_TAG.test(note[1])) out.pending.push(`${row[1]}: ${note[1]}`);
        text = text.slice(0, note.index).trim();
      }
      if (HERO_TAG.test(text)) { out.pending.push(`${row[1]}: ${text}`); continue; }
      sliverRows.push({ id: row[1], from, to, text });
      continue;
    }
    if (/^\|/.test(raw) && !/^\| (id|---)/.test(raw)) refuse(lineNo, 'a sliver row the table does not understand', raw);
    continue;
  }

  if (section.startsWith('between chapters — story lines')) {
    const head = raw.match(/^\*\*(ch\d+) → (ch\d+)\*\*$/) || raw.match(/^\*\*after (ch\d+) — .*\*\*$/);
    if (head) {
      linesWindow = { from: head[1], to: head[2] || null, items: [] };
      lineGroups.push(linesWindow);
      continue;
    }
    const b = raw.match(/^- (.*)$/);
    if (b) {
      if (!linesWindow) refuse(lineNo, 'a story line before its window heading', raw);
      let text = b[1].trim();
      const item = {};
      const met = text.match(/\s*`\?met:([a-z]+)`\s*$/);
      if (met) { item.met = met[1]; text = text.slice(0, met.index).trim(); }
      if (HERO_TAG.test(text)) { out.pending.push(`line: ${text}`); continue; }
      item.text = text;
      linesWindow.items.push(item);
    }
    continue;
  }

  if (section === 'the villagers') {
    const b = raw.match(/^- \*\*([^*]+):\*\* (.*)$/);
    if (villager && b) {
      const key = b[1].trim();
      const items = splitItems(b[2]);
      if (['greet', 'waiting', 'delivered'].includes(key)) { villager[key].push(...items); continue; }
      const am = key.match(/^after (ch\d+)(?: \((.*)\))?$/);
      if (am) {
        const entry = { lines: items };
        if (am[2]) {
          const rule = POOL_NOTES[am[2].toLowerCase()];
          if (!rule) refuse(lineNo, `unknown pool note (${am[2]})`, raw);
          Object.assign(entry, rule);
        }
        villager.after[am[1]] = entry;
        continue;
      }
      refuse(lineNo, `unknown pool ${key}`, raw);
    }
    // Existing villagers: "- **Bram, after ch4:** …" or Wren's mixed line.
    const ex = raw.match(/^- \*\*([A-Z][a-z]+(?: [A-Z][a-z]+)?), after (ch\d+):\*\* (.*)$/);
    if (ex) {
      const id = NAME_TO_ID[ex[1].toLowerCase()];
      if (!id) refuse(lineNo, `unknown villager ${ex[1]}`, raw);
      const v = out.villagers[id] = out.villagers[id] || { greet: [], waiting: [], delivered: [], after: {} };
      v.after[ex[2]] = { lines: splitItems(ex[3]) };
      continue;
    }
    const wm = raw.match(/^- \*\*(Wren)\*\* \([^)]*\): (.*)$/);
    if (wm) {
      const v = out.villagers.wren = out.villagers.wren || { greet: [], waiting: [], delivered: [], after: {} };
      const parts = wm[2].split(/\*\*([a-z0-9 ]+):\*\*/).map((x) => x.trim());
      for (let k = 1; k < parts.length; k += 2) {
        const key = parts[k];
        const items = stripShipped(splitItems(parts[k + 1] || ''));
        if (['greet', 'waiting', 'delivered'].includes(key)) v[key].push(...items);
        else if (/^after ch\d+$/.test(key)) v.after[key.slice(6)] = { lines: items };
        else refuse(lineNo, `unknown pool ${key}`, raw);
      }
      continue;
    }
    if (/^- /.test(raw)) refuse(lineNo, 'a villager line the format does not know', raw);
    continue;
  }

  if (section.startsWith('the welcome-back board')) {
    const b = raw.match(/^- \*\*([A-Za-z]+):\*\* (.*)$/);
    if (b) {
      const id = NAME_TO_ID[b[1].toLowerCase()];
      if (!id) refuse(lineNo, `unknown villager ${b[1]}`, raw);
      out.welcome[id] = splitItems(b[2]);
      continue;
    }
    if (/^- /.test(raw)) refuse(lineNo, 'a welcome line the format does not know', raw);
    continue;
  }

  if (section.startsWith("poppy's voice")) {
    const row = raw.match(/^\| ([a-z]+) \| ([^|]+) \| ([^|]+) \|$/);
    if (row && row[1] !== 'bucket') { out.flowerLines.push({ bucket: row[1], from: row[2].trim(), to: row[3].trim() }); continue; }
    const tl = raw.match(/^- (toddler|child|wry): (.*)$/);
    if (tl) { out.turnLines[tl[1]] = tl[2].trim(); continue; }
    if (/^- /.test(raw)) refuse(lineNo, 'a Turn line the format does not know', raw);
    continue;
  }

  if (section.startsWith('holly')) {
    const row = raw.match(/^\| ([^|]+) \| ([^|]+) \|$/);
    if (row && !/^(Shipped|---)/.test(row[1].trim())) { out.holly.push({ from: row[1].trim(), to: row[2].trim() }); continue; }
    continue;
  }
}
if (inFence) refuse(src.length, 'the file ends inside a fence');
closeChapter();

/* ---------- checks the format promises ---------- */
out.chapters.forEach((ch) => {
  if (ch.level == null) refuse(0, `${ch.id} has no @level`);
  if (!ch.title) refuse(0, `${ch.id} has no title`);
  ch.scenes.forEach((sc) => {
    if (!sc.lines.some((l) => l.mode !== 'stage')) refuse(0, `${sc.id} has no lines`);
    sc.lines.forEach((l) => {
      if (l.who && l.who !== 'note' && l.who !== 'poppy' && !sc.faces.includes(l.who)) {
        refuse(0, `${sc.id}: ${l.who} speaks but is not one of the scene's faces`);
      }
    });
  });
  const vill = ch.change.filter((c) => c.kind === 'villager').map((c) => c.value);
  vill.forEach((v) => {
    if (!out.villagers[v] || out.villagers[v].arrives !== ch.id) refuse(0, `${ch.id} says villager:${v} but the villagers section disagrees`);
  });
});
Object.entries(out.villagers).forEach(([id, v]) => {
  if (v.arrives && !chapterById(v.arrives)) refuse(0, `${id} arrives at ${v.arrives}, which does not exist`);
  if (v.arrives && !['greet', 'waiting', 'delivered'].every((k) => v[k].length)) refuse(0, `${id} arrives with an empty pool`);
});
const order = out.chapters.map((c) => c.n);
if (order.some((n, i) => n !== i + 1)) refuse(0, 'chapters are not ch1..chN in order');
if (!chapterById('ch1').runs || !['open', 'hum', 'teach', 'ask'].every((k) => chapterById('ch1').runs[k])) {
  refuse(0, 'Chapter I needs its open, hum, teach and ask runs');
}

/* ---------- levels for the between-chapter kinds ---------- */
const AFTER_SPAN = 10;
{
  const groups = {};
  sliverRows.forEach((r) => { const k = `${r.from}|${r.to}`; (groups[k] = groups[k] || []).push(r); });
  Object.values(groups).forEach((g) => {
    if (g[0].to === null) g.forEach((r) => { r.level = levelOf(r.from); });
    else spread(g, g[0].from, g[0].to, AFTER_SPAN);
  });
  const ids = sliverRows.map((r) => r.id);
  if (ids.some((id, i) => id !== `m${String(i + 1).padStart(2, '0')}`)) refuse(0, 'slivers are not m01..mNN in order');
  out.slivers = sliverRows.map((r) => ({ id: r.id, from: r.from, level: r.level, text: r.text }));
}
{
  let n = 0;
  lineGroups.forEach((g) => {
    spread(g.items, g.from, g.to, AFTER_SPAN);
    g.items.forEach((it) => {
      n += 1;
      const row = { id: `l${String(n).padStart(3, '0')}`, from: g.from, level: it.level, text: it.text };
      if (it.met) row.met = it.met;
      out.lines.push(row);
    });
  });
}

/* ---------- write ---------- */
function lit(v, ind) {
  const pad = '  '.repeat(ind);
  const padIn = '  '.repeat(ind + 1);
  if (v === null) return 'null';
  if (typeof v === 'string') return `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) {
    if (!v.length) return '[]';
    const flat = v.every((x) => typeof x !== 'object' || x === null);
    const parts = v.map((x) => lit(x, ind + 1));
    const one = `[${parts.join(', ')}]`;
    if (flat && one.length + pad.length < 110) return one;
    if (v.every((x) => x && typeof x === 'object' && !Array.isArray(x))) {
      const inline = v.map((x) => lit(x, ind + 1));
      if (inline.every((s) => !s.includes('\n') && s.length + padIn.length < 150)) return `[\n${inline.map((s) => padIn + s).join(',\n')}\n${pad}]`;
    }
    return `[\n${parts.map((s) => padIn + s).join(',\n')}\n${pad}]`;
  }
  const keys = Object.keys(v).filter((k) => v[k] !== undefined);
  if (!keys.length) return '{}';
  const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`);
  const parts = keys.map((k) => `${key(k)}: ${lit(v[k], ind + 1)}`);
  const one = `{ ${parts.join(', ')} }`;
  if (!one.includes('\n') && one.length + pad.length < 150) return one;
  return `{\n${parts.map((s) => padIn + s).join(',\n')}\n${pad}}`;
}

